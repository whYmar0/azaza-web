"""Источник ответа: классическая головоломка с Wikipedia
(File:Sudoku Puzzle by L2G-20050714 standardized layout.svg) — 30
подсказок, единственное решение. Ответ известен до кода: головоломка
опубликована вместе с ответом.
"""

from core.solver import solve

# Эталон 1: опубликованная головоломка + её опубликованный ответ.
P = "53..7....6..195....98....6.8...6...34..8.3..17...2...6.6....28....419..5....8..79"
S = "534678912672195348198342567859761423426853791713924856961537284287419635345286179"


def test_solves_published_puzzle():
    """30 подсказок, единственное решение, ответ известен из Wikipedia."""
    assert solve(P) == S


# Эталон 2: у S стёрты 4 клетки крест-накрест -> решений становится
# ровно два (проверено отдельным скриптом: оба решения найдены и
# отличаются только в этих 4 клетках).
AMBIG = "".join("." if i in (32, 35, 41, 44) else c for i, c in enumerate(S))


def test_ambiguous_grid_is_multiple():
    """Сетка с несколькими решениями — solve() возвращает 'multiple'."""
    assert solve(AMBIG) == "multiple"


def test_empty_grid_is_multiple():
    """Пустая сетка имеет множество решений — не 'no solution', а 'multiple'."""
    assert solve("." * 81) == "multiple"
